"""Render `ontology/schema.ttl` from `ontology/registry.py`.

The TTL is a generated artifact: classes come from `registry.NODES`, object
properties from `registry.EDGES`. A relationship type shared by several rules
gets the union of their labels as `rdfs:domain` / `rdfs:range`
(`owl:unionOf`), and every object property carries `mfg:cypherType` — the
UPPER_SNAKE relationship type the loader writes and the API queries.

    python -m ontology.build_ttl            # rewrite ontology/schema.ttl
    python -m ontology.build_ttl --check    # exit 1 if schema.ttl is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ontology import registry as reg

SCHEMA_PATH = Path(__file__).resolve().parent / "schema.ttl"


def _lit(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _class_expr(labels: list[str]) -> str:
    if len(labels) == 1:
        return f"mfg:{labels[0]}"
    members = " ".join(f"mfg:{lbl}" for lbl in labels)
    return f"[ a owl:Class ; owl:unionOf ( {members} ) ]"


def _derivation(e: reg.EdgeSpec) -> str:
    how = {
        "fk": f"{e.record}.{e.field}",
        "fk_list": f"{e.record}.{e.field}[]",
        "objects": f"{e.record}.{e.field}[].{e.key}",
        "join": f"{e.record}.{e.field} = {e.target}.{e.join_field}",
    }[e.kind]
    return f"{e.src} -> {e.dst} ({how})"


def render_ttl() -> str:
    out: list[str] = [
        "# GENERATED by `python -m ontology.build_ttl` from ontology/registry.py",
        "# — do not edit by hand; change the registry and regenerate.",
        "@prefix owl:  <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        f"@prefix mfg:  <{reg.NAMESPACE}> .",
        "",
        "mfg:cypherType a owl:AnnotationProperty ;",
        '    rdfs:label "cypherType" ;',
        '    rdfs:comment "openCypher relationship type (Neptune property graph) that materialises this object property." .',
        "",
        f"# ==== Classes ({len(reg.NODES)}) ====",
    ]
    for group, title in reg.GROUPS.items():
        members = [n for n in reg.NODES if n.group == group]
        if not members:
            continue
        out.append("")
        out.append(f"# {title} ({len(members)})")
        for n in members:
            out.append(f"mfg:{n.label} a owl:Class ; rdfs:label {_lit(n.label)} .")

    rels = reg.rel_types()
    out.append("")
    out.append(
        f"# ==== Object Properties ({len(rels)}) — domain / range = union over registry rules ===="
    )
    for rel in rels:
        rules = reg.rules_for(rel)
        dom, rng = reg.endpoints(rel)
        ttl = rules[0].ttl
        comment = "; ".join(_derivation(e) for e in rules)
        out.append("")
        out.append(f"mfg:{ttl} a owl:ObjectProperty ;")
        out.append(f"    rdfs:label {_lit(ttl)} ;")
        out.append(f"    mfg:cypherType {_lit(rel)} ;")
        out.append(f"    rdfs:comment {_lit(comment)} ;")
        out.append(f"    rdfs:domain {_class_expr(dom)} ;")
        out.append(f"    rdfs:range {_class_expr(rng)} .")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--check", action="store_true", help="fail if schema.ttl differs from the registry"
    )
    p.add_argument("--out", type=Path, default=SCHEMA_PATH)
    args = p.parse_args(argv)
    errors = reg.validate()
    if errors:
        print("registry invalid:\n  " + "\n  ".join(errors), file=sys.stderr)
        return 2
    text = render_ttl()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is stale — run `python -m ontology.build_ttl`", file=sys.stderr)
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
